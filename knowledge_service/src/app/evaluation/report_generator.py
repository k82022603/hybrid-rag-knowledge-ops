"""
RAGAS 평가 리포트 생성기

평가 결과를 Markdown 및 JSON 형식으로 출력합니다.

사용 예시:
    from app.evaluation.report_generator import RagasReportGenerator

    generator = RagasReportGenerator()
    md_report = generator.generate_markdown(response)
    generator.save_reports(response, output_dir="/path/to/reports")
"""

import json
import os
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

from app.evaluation.models import EvaluationResponse, EvaluationResult, MetricScores


class RagasReportGenerator:
    """
    RAGAS 평가 리포트 생성기

    평가 결과를 다양한 형식(Markdown, JSON)으로 변환하고 저장합니다.

    Attributes:
        project_name: 프로젝트 이름 (리포트 헤더에 표시)
        include_details: 개별 샘플 상세 결과 포함 여부

    Example:
        >>> generator = RagasReportGenerator(project_name="Hybrid RAG")
        >>> md_report = generator.generate_markdown(response)
        >>> generator.save_reports(response, output_dir="reports")
    """

    def __init__(
        self,
        project_name: str = "Hybrid RAG Knowledge Platform",
        include_details: bool = True,
    ):
        """
        초기화

        Args:
            project_name: 프로젝트 이름
            include_details: 개별 샘플 상세 결과 포함 여부
        """
        self.project_name = project_name
        self.include_details = include_details

    def generate_markdown(
        self,
        response: EvaluationResponse,
        targets: Optional[Dict[str, float]] = None,
    ) -> str:
        """
        Markdown 리포트 생성

        Args:
            response: 평가 응답 객체
            targets: 목표 점수 딕셔너리 (없으면 summary에서 추출)

        Returns:
            Markdown 형식 리포트 문자열
        """
        targets = targets or response.summary.get("targets", {})
        meets_targets = response.summary.get("meets_targets", {})

        lines: List[str] = []

        # 헤더
        lines.append(f"# RAGAS 평가 리포트")
        lines.append("")
        lines.append(f"**프로젝트**: {self.project_name}")
        lines.append(f"**평가 시간**: {response.timestamp.strftime('%Y-%m-%d %H:%M:%S UTC')}")
        lines.append(f"**평가 샘플 수**: {response.total_samples}")
        lines.append("")

        # 요약 테이블
        lines.append("## 평가 요약")
        lines.append("")
        lines.append("| 지표 | 점수 | 목표 | 달성 여부 |")
        lines.append("|------|------|------|----------|")

        metric_names = {
            "faithfulness": "Faithfulness (충실도)",
            "answer_relevancy": "Answer Relevancy (답변 관련성)",
            "context_precision": "Context Precision (컨텍스트 정밀도)",
            "context_recall": "Context Recall (컨텍스트 재현율)",
        }

        scores = response.aggregate_scores
        for metric, display_name in metric_names.items():
            score = getattr(scores, metric)
            target = targets.get(metric, 0.7)
            passed = meets_targets.get(metric)

            if score is not None:
                score_str = f"{score:.4f}"
                status = "PASS" if passed else "FAIL"
                status_emoji = "v" if passed else "x"
            else:
                score_str = "N/A"
                status = "-"
                status_emoji = "-"

            lines.append(f"| {display_name} | {score_str} | {target:.2f} | {status_emoji} {status} |")

        lines.append("")

        # 통과율
        lines.append("### 통과율")
        lines.append("")
        lines.append(f"- **통과 샘플**: {response.passed_samples} / {response.total_samples}")
        lines.append(f"- **통과율**: {response.pass_rate:.1%}")
        lines.append("")

        # 전체 결과
        all_passed = all(meets_targets.values()) if meets_targets else False
        if all_passed:
            lines.append("> **[SUCCESS]** 모든 목표 점수를 달성했습니다!")
        else:
            failed_metrics = [m for m, p in meets_targets.items() if not p]
            lines.append(f"> **[FAIL]** 목표 미달 지표: {', '.join(failed_metrics)}")

        lines.append("")

        # 지표별 분포
        lines.append("## 지표별 점수 분포")
        lines.append("")
        self._add_metric_distribution(lines, response.results, scores)

        # 개별 샘플 결과
        if self.include_details and response.results:
            lines.append("## 개별 샘플 결과")
            lines.append("")
            self._add_sample_details(lines, response.results, targets)

        # 권장 사항
        lines.append("## 개선 권장 사항")
        lines.append("")
        self._add_recommendations(lines, scores, targets)

        # 푸터
        lines.append("---")
        lines.append("")
        lines.append(f"*Generated by RAGAS Evaluation Pipeline - {datetime.now().strftime('%Y-%m-%d')}*")

        return "\n".join(lines)

    def _add_metric_distribution(
        self,
        lines: List[str],
        results: List[EvaluationResult],
        aggregate_scores: MetricScores,
    ) -> None:
        """지표별 점수 분포 섹션 추가"""
        metrics = ["faithfulness", "answer_relevancy", "context_precision", "context_recall"]

        for metric in metrics:
            scores = [
                getattr(r.scores, metric)
                for r in results
                if getattr(r.scores, metric) is not None
            ]

            if not scores:
                continue

            min_score = min(scores)
            max_score = max(scores)
            avg_score = sum(scores) / len(scores)

            lines.append(f"### {metric.replace('_', ' ').title()}")
            lines.append("")
            lines.append(f"- **평균**: {avg_score:.4f}")
            lines.append(f"- **최소**: {min_score:.4f}")
            lines.append(f"- **최대**: {max_score:.4f}")
            lines.append(f"- **샘플 수**: {len(scores)}")
            lines.append("")

    def _add_sample_details(
        self,
        lines: List[str],
        results: List[EvaluationResult],
        targets: Dict[str, float],
    ) -> None:
        """개별 샘플 상세 결과 섹션 추가"""
        # 결과를 통과/실패로 분류
        passed_results = [r for r in results if r.passed]
        failed_results = [r for r in results if not r.passed]

        if failed_results:
            lines.append("### 실패 샘플 (상세)")
            lines.append("")
            for result in failed_results[:10]:  # 상위 10개만
                lines.append(f"#### {result.sample_id}")
                lines.append(f"- **질문**: {result.question[:100]}{'...' if len(result.question) > 100 else ''}")

                score_parts = []
                if result.scores.faithfulness is not None:
                    score_parts.append(f"Faithfulness: {result.scores.faithfulness:.4f}")
                if result.scores.answer_relevancy is not None:
                    score_parts.append(f"Relevancy: {result.scores.answer_relevancy:.4f}")
                if result.scores.context_precision is not None:
                    score_parts.append(f"Precision: {result.scores.context_precision:.4f}")

                lines.append(f"- **점수**: {' | '.join(score_parts)}")
                lines.append("")

        lines.append(f"### 통계")
        lines.append("")
        lines.append(f"- 통과: {len(passed_results)} 샘플")
        lines.append(f"- 실패: {len(failed_results)} 샘플")
        lines.append("")

    def _add_recommendations(
        self,
        lines: List[str],
        scores: MetricScores,
        targets: Dict[str, float],
    ) -> None:
        """개선 권장 사항 섹션 추가"""
        recommendations = []

        # Faithfulness 개선
        if scores.faithfulness and scores.faithfulness < targets.get("faithfulness", 0.7):
            recommendations.append(
                "**Faithfulness 개선**: 답변이 컨텍스트에 더 충실하도록 프롬프트를 개선하세요. "
                "환각(hallucination)을 줄이기 위해 '컨텍스트에 없는 내용은 추측하지 마세요' 지시를 강화하세요."
            )

        # Answer Relevancy 개선
        if scores.answer_relevancy and scores.answer_relevancy < targets.get("answer_relevancy", 0.7):
            recommendations.append(
                "**Answer Relevancy 개선**: 답변이 질문에 더 직접적으로 응답하도록 개선하세요. "
                "질문의 핵심 키워드를 답변에 포함하고, 불필요한 정보를 줄이세요."
            )

        # Context Precision 개선
        if scores.context_precision and scores.context_precision < targets.get("context_precision", 0.7):
            recommendations.append(
                "**Context Precision 개선**: 검색 품질을 높이세요. "
                "Reranker 적용, 임베딩 모델 최적화, 또는 청킹 전략 조정을 고려하세요."
            )

        # Context Recall 개선
        if scores.context_recall and scores.context_recall < targets.get("context_recall", 0.7):
            recommendations.append(
                "**Context Recall 개선**: 관련 정보가 누락되지 않도록 검색 범위를 확대하세요. "
                "top_k 증가, Hybrid Search 가중치 조정, 또는 Graph Search 활용을 검토하세요."
            )

        if recommendations:
            for rec in recommendations:
                lines.append(f"- {rec}")
        else:
            lines.append("- 모든 목표 점수를 달성했습니다. 현재 설정을 유지하세요.")

        lines.append("")

    def generate_json(
        self,
        response: EvaluationResponse,
    ) -> Dict[str, Any]:
        """
        JSON 리포트 생성

        Args:
            response: 평가 응답 객체

        Returns:
            JSON 변환 가능한 딕셔너리
        """
        return {
            "timestamp": response.timestamp.isoformat(),
            "total_samples": response.total_samples,
            "passed_samples": response.passed_samples,
            "pass_rate": response.pass_rate,
            "aggregate_scores": {
                "faithfulness": response.aggregate_scores.faithfulness,
                "answer_relevancy": response.aggregate_scores.answer_relevancy,
                "context_precision": response.aggregate_scores.context_precision,
                "context_recall": response.aggregate_scores.context_recall,
                "average": response.aggregate_scores.average(),
            },
            "summary": response.summary,
            "results": [
                {
                    "sample_id": r.sample_id,
                    "question": r.question,
                    "passed": r.passed,
                    "scores": {
                        "faithfulness": r.scores.faithfulness,
                        "answer_relevancy": r.scores.answer_relevancy,
                        "context_precision": r.scores.context_precision,
                        "context_recall": r.scores.context_recall,
                    },
                    "details": r.details,
                }
                for r in response.results
            ],
        }

    def save_reports(
        self,
        response: EvaluationResponse,
        output_dir: str,
        base_name: Optional[str] = None,
        targets: Optional[Dict[str, float]] = None,
    ) -> Dict[str, str]:
        """
        리포트 파일 저장

        JSON과 Markdown 형식으로 동시에 저장합니다.

        Args:
            response: 평가 응답 객체
            output_dir: 출력 디렉토리 경로
            base_name: 파일 기본 이름 (None이면 타임스탬프 사용)
            targets: 목표 점수 딕셔너리

        Returns:
            저장된 파일 경로 딕셔너리 {"json": path, "markdown": path}
        """
        output_path = Path(output_dir)
        output_path.mkdir(parents=True, exist_ok=True)

        if base_name is None:
            timestamp = response.timestamp.strftime("%Y-%m-%d_%H%M%S")
            base_name = f"ragas_evaluation_{timestamp}"

        saved_files = {}

        # JSON 저장
        json_path = output_path / f"{base_name}.json"
        json_data = self.generate_json(response)
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(json_data, f, ensure_ascii=False, indent=2)
        saved_files["json"] = str(json_path)

        # Markdown 저장
        md_path = output_path / f"{base_name}.md"
        md_content = self.generate_markdown(response, targets)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)
        saved_files["markdown"] = str(md_path)

        return saved_files


# 싱글톤 인스턴스
_generator: Optional[RagasReportGenerator] = None


def get_report_generator() -> RagasReportGenerator:
    """RagasReportGenerator 인스턴스 반환 (싱글톤)"""
    global _generator
    if _generator is None:
        _generator = RagasReportGenerator()
    return _generator
